type MockUsdBundle = {
	readonly address: `0x${string}`;
	abi: unknown;
};

type WalletDeployed = Awaited<ReturnType<typeof hre.viem.getWalletClient>>;
type PublicClientDeployed = Awaited<
	ReturnType<typeof hre.viem.getPublicClient>
>;

export type LocalMockUsdBundle = MockUsdBundle;

export function viemChainOverride(): { chain: typeof hardhat } | undefined {
	if (hre.network.name === "localhost") {
		return { chain: hardhat };
	}
	return undefined;
}

export async function fundLocalRelayer(
	deployer: WalletDeployed,
	publicClient: PublicClientDeployed,
	relayerAddress: `0x${string}`,
) {
	const min = parseEther("1");
	const balance = await publicClient.getBalance({ address: relayerAddress });
	if (balance >= min) return;

	const hash = await deployer.sendTransaction({
		account: deployer.account,
		to: relayerAddress,
		value: parseEther("100"),
	});
	await publicClient.waitForTransactionReceipt({ hash });
	console.log("Funded relayer:", relayerAddress);
}

export async function fundLocalMockUsdcRecipientForGas(
	deployer: WalletDeployed,
	publicClient: PublicClientDeployed,
	recipientAddress: `0x${string}`,
) {
	// Settlement rules require payer gas (native ETH), even if USDC is the token being transferred.
	const min = parseEther("1");
	const balance = await publicClient.getBalance({ address: recipientAddress });
	if (balance >= min) return;

	const hash = await deployer.sendTransaction({
		account: deployer.account,
		to: recipientAddress,
		value: parseEther("10"),
	});
	await publicClient.waitForTransactionReceipt({ hash });
	console.log("Funded local MockUSDC recipient for gas:", recipientAddress);
}

export async function deployAndFundLocalMockUsd(
	deployer: WalletDeployed,
	publicClient: PublicClientDeployed,
): Promise<MockUsdBundle> {
	const mockUsdc = await hre.viem.deployContract(
		"MockUSDCToken",
		[deployer.account.address],
		{ client: { wallet: deployer } },
	);

	const bundle: MockUsdBundle = {
		address: getAddress(mockUsdc.address),
		abi: mockUsdc.abi,
	};

	const mint = mockUsdc.write.mint;
	if (!mint) {
		throw new Error("MockUSDCToken.mint unavailable");
	}
	const mintHash = await mint([
		LOCAL_MOCK_USDC_RECIPIENT,
		LOCAL_MOCK_USDC_MINT_AMOUNT,
	]);
	await publicClient.waitForTransactionReceipt({ hash: mintHash });
	return bundle;
}

